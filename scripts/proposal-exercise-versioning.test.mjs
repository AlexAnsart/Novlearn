// Disposable PGlite smoke test for the non-executable DDL proposal.
// The digest routine is stubbed: this checks trigger wiring/constraints, not SHA-256.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const ddl = await readFile(
  new URL("../docs/sql-proposals/20261013-exercise-versioning.proposal.sql.txt", import.meta.url),
  "utf8",
);
const db = new PGlite();

try {
  await db.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE SCHEMA extensions;
    CREATE FUNCTION extensions.digest(bytea, text) RETURNS bytea
      LANGUAGE sql IMMUTABLE AS $$ SELECT decode(repeat('00', 32), 'hex') $$;
    CREATE TABLE public.exercises (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      content jsonb
    );
    CREATE TABLE public.exercise_attempts (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      exercise_id bigint
    );
    CREATE TABLE public.duels (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    );
    CREATE TABLE public.duel_attempts (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      duel_id bigint
    );
  `);
  await db.exec(ddl);

  await db.exec(`
    INSERT INTO public.exercises (id, content) VALUES (1, '{"legacy":true}');
    INSERT INTO public.exercises (id, content) VALUES (2, '{"legacy":true}');
    INSERT INTO public.exercise_attempts (exercise_id) VALUES (1);
    INSERT INTO public.exercise_versions (
      id, exercise_id, revision, definition, engine_contract, generation_version,
      canonicalization_version, definition_sha256
    ) VALUES (
      '10000000-0000-0000-0000-000000000001', 1, 1, '{"schema":5}', '5', '1',
      'jsonb-text-v1', repeat('a', 64)
    );
    UPDATE public.exercise_versions SET editorial_status='approved',
      approved_at=now(), approved_by='20000000-0000-0000-0000-000000000001'
      WHERE id='10000000-0000-0000-0000-000000000001';
    UPDATE public.exercise_versions SET editorial_status='published'
      WHERE id='10000000-0000-0000-0000-000000000001';
    UPDATE public.exercises SET active_version_id='10000000-0000-0000-0000-000000000001'
      WHERE id=1;
    INSERT INTO public.exercise_attempts (
      exercise_id, exercise_version_id, instance_id, instance_seed,
      generation_version
    ) VALUES (
      1, '10000000-0000-0000-0000-000000000001',
      '30000000-0000-0000-0000-000000000001', '42', '1'
    );
    INSERT INTO public.exercise_attempt_replay_artifacts (attempt_id, replay_data)
      VALUES (2, '{"private_answer":"secret"}');
    INSERT INTO public.duels (id) VALUES (7);
    INSERT INTO public.duel_exercise_instances (
      id, duel_id, round_number, exercise_id, exercise_version_id,
      instance_seed, generation_version, replay_data
    ) VALUES (
      '40000000-0000-0000-0000-000000000001', 7, 1, 1,
      '10000000-0000-0000-0000-000000000001', '42', '1', '{"private":true}'
    );
    INSERT INTO public.duel_attempts (duel_id, duel_exercise_instance_id)
      VALUES (7, '40000000-0000-0000-0000-000000000001');
  `);

  const historic = await db.query(`
    SELECT exercise_id, exercise_version_id, instance_id FROM public.exercise_attempts ORDER BY id
  `);
  assert.deepEqual(historic.rows[0], { exercise_id: 1, exercise_version_id: null, instance_id: null });
  assert.equal(historic.rows[1].exercise_version_id, "10000000-0000-0000-0000-000000000001");

  await assert.rejects(
    db.exec(`UPDATE public.exercise_versions SET definition='{"changed":true}'
      WHERE id='10000000-0000-0000-0000-000000000001'`),
    /immutable/,
  );
  await assert.rejects(
    db.exec(`DELETE FROM public.exercise_versions
      WHERE id='10000000-0000-0000-0000-000000000001'`),
    /immutable/,
  );
  await assert.rejects(
    db.exec(`UPDATE public.exercises SET active_version_id='10000000-0000-0000-0000-000000000001' WHERE id=2`),
    /active exercise version must be published/,
  );
  await db.exec(`
    INSERT INTO public.exercise_versions (
      exercise_id, revision, definition, engine_contract, generation_version,
      canonicalization_version, definition_sha256, editorial_status
    ) VALUES (1, 2, '{"schema":5}', '5', '1', 'jsonb-text-v1', repeat('f',64), 'draft');
    UPDATE public.exercise_versions SET editorial_status='approved',
      approved_at=now(), approved_by='20000000-0000-0000-0000-000000000001'
      WHERE exercise_id=1 AND revision=2;
    UPDATE public.exercise_versions SET engine_contract='6'
      WHERE exercise_id=1 AND revision=2;
  `);
  const invalidated = await db.query(`SELECT editorial_status, approved_at,
    approved_by, approved_fingerprint_sha256 FROM public.exercise_versions WHERE revision=2`);
  assert.deepEqual(invalidated.rows[0], {
    editorial_status: "draft",
    approved_at: null,
    approved_by: null,
    approved_fingerprint_sha256: null,
  });
  await db.exec(`
    UPDATE public.exercise_versions SET editorial_status='approved',
      approved_at=now(), approved_by='20000000-0000-0000-0000-000000000001'
      WHERE exercise_id=1 AND revision=2;
    UPDATE public.exercise_versions SET approved_by='20000000-0000-0000-0000-000000000002'
      WHERE exercise_id=1 AND revision=2;
  `);
  const approvalEdit = await db.query(`SELECT editorial_status, approved_by
    FROM public.exercise_versions WHERE revision=2`);
  assert.deepEqual(approvalEdit.rows[0], { editorial_status: "draft", approved_by: null });
  await assert.rejects(
    db.exec(`INSERT INTO public.exercise_versions (
      exercise_id, revision, definition, engine_contract, generation_version,
      canonicalization_version, definition_sha256, editorial_status
    ) VALUES (1, 3, '{}', '5', '1', 'jsonb-text-v1', repeat('0',64), 'published')`),
    /insert a draft/,
  );
  await assert.rejects(
    db.exec(`SET ROLE authenticated; SELECT * FROM public.exercise_attempt_replay_artifacts`),
    /permission denied/,
  );
  await assert.rejects(
    db.exec(`INSERT INTO public.duel_attempts (duel_id, duel_exercise_instance_id)
      VALUES (8, '40000000-0000-0000-0000-000000000001')`),
    /foreign key constraint/,
  );
  await assert.rejects(
    db.exec(`SET ROLE authenticated; SELECT * FROM public.exercise_versions`),
    /permission denied/,
  );

  const hash = await db.query(`SELECT definition_sha256 FROM public.exercise_versions LIMIT 1`);
  assert.equal(hash.rows[0].definition_sha256, "00".repeat(32));
  const approval = await db.query(`SELECT approved_fingerprint_sha256, approval_fingerprint_sha256 FROM public.exercise_versions WHERE revision=1`);
  assert.equal(approval.rows[0].approved_fingerprint_sha256, approval.rows[0].approval_fingerprint_sha256);
  process.stdout.write("Proposal smoke test passed (digest implementation stubbed; RLS not tested).\n");
} finally {
  await db.close();
}
